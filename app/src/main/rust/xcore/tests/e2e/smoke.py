import sys, time
from Xlib import X, display, Xatom, error
d = display.Display(sys.argv[1])
s = d.screen()
print("root", hex(s.root.id), "size", s.width_in_pixels, s.height_in_pixels, "depth", s.root_depth)
print("vendor", d.display.info.vendor, "release", d.display.info.release_number)
print("visuals", [(dp.depth, [(v.visual_id, v.red_mask) for v in dp.visuals]) for dp in s.allowed_depths])
print("formats", [(f.depth, f.bits_per_pixel, f.scanline_pad) for f in d.display.info.pixmap_formats])
print("keycodes", d.display.info.min_keycode, d.display.info.max_keycode)
print("extensions", d.list_extensions())
print("bigreq", d.query_extension("BIG-REQUESTS"))
a = d.intern_atom("WM_NAME"); print("WM_NAME", a, d.get_atom_name(a))
w = s.root.create_window(10, 20, 200, 100, 0, s.root_depth, X.InputOutput, X.CopyFromParent, event_mask=X.StructureNotifyMask|X.ExposureMask)
w.change_property(Xatom.WM_NAME, Xatom.STRING, 8, b"hello")
print("prop", w.get_full_property(Xatom.WM_NAME, X.AnyPropertyType).value)
w.map()
d.sync()
g = w.get_geometry(); print("geom", g.x, g.y, g.width, g.height)
print("tree", [hex(c.id) for c in s.root.query_tree().children])
n = d.pending_events()
while d.pending_events():
    e = d.next_event(); print("event", type(e).__name__)
w.destroy(); d.sync()
print("ok")
